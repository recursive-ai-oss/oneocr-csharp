// Generates src/OneOcr/Unicode/NormalizationTables.g.cs from the Unicode Character Database.
//
//   dotnet run --project tools/NormalizationTables -- <ucd-dir> <output.cs>
//
// <ucd-dir> holds UnicodeData.txt and CompositionExclusions.txt of the pinned version below; their SHA-256 are checked, so a
// different file cannot slip in. The tables follow UAX #15 (Unicode Normalization Forms):
//   * ccc            canonical combining class ranges (UnicodeData field 3)
//   * canonical      full canonical decomposition of every character that has one (Hangul syllables are algorithmic, not listed)
//   * compat         full compatibility decomposition of every character whose expansion differs from its canonical one
//   * composition    primary composites: canonical pair decompositions minus CompositionExclusions.txt and non-starter decompositions
using System.Globalization;
using System.Security.Cryptography;
using System.Text;

const string UcdVersion = "17.0.0";
const string UnicodeDataSha256 = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c";
const string ExclusionsSha256 = "2f239196ef3b5b61db5cc476e9bd80f534d15aa1b74e1be1dea5d042a344c85f";

if (args.Length != 2)
{
    Console.Error.WriteLine("usage: NormalizationTables <ucd-dir> <output.cs>");
    return 2;
}

string dataPath = Path.Combine(args[0], "UnicodeData.txt");
string exclPath = Path.Combine(args[0], "CompositionExclusions.txt");
Check(dataPath, UnicodeDataSha256);
Check(exclPath, ExclusionsSha256);

var ccc = new SortedDictionary<int, int>();
var rawDecomp = new SortedDictionary<int, (bool Compat, int[] Map)>();
foreach (string line in File.ReadLines(dataPath))
{
    if (line.Length == 0)
    {
        continue;
    }

    string[] f = line.Split(';');
    int cp = int.Parse(f[0], NumberStyles.HexNumber, CultureInfo.InvariantCulture);
    int c = int.Parse(f[3], CultureInfo.InvariantCulture);
    if (c != 0)
    {
        ccc[cp] = c;
    }

    string d = f[5];
    if (d.Length > 0)
    {
        bool compat = d[0] == '<';
        if (compat)
        {
            d = d[(d.IndexOf('>') + 1)..].Trim();
        }

        int[] map = [.. d.Split(' ', StringSplitOptions.RemoveEmptyEntries).Select(x => int.Parse(x, NumberStyles.HexNumber, CultureInfo.InvariantCulture))];
        rawDecomp[cp] = (compat, map);
    }
}

var exclusions = new HashSet<int>();
foreach (string line in File.ReadLines(exclPath))
{
    string t = line.Split('#')[0].Trim();
    if (t.Length > 0)
    {
        exclusions.Add(int.Parse(t, NumberStyles.HexNumber, CultureInfo.InvariantCulture));
    }
}

List<int> Expand(int cp, bool compat)
{
    var result = new List<int>();
    if (rawDecomp.TryGetValue(cp, out var d) && (compat || !d.Compat))
    {
        foreach (int x in d.Map)
        {
            result.AddRange(Expand(x, compat));
        }
    }
    else
    {
        result.Add(cp);
    }

    return result;
}

var canonical = new SortedDictionary<int, List<int>>();
var compatibility = new SortedDictionary<int, List<int>>();
foreach (int cp in rawDecomp.Keys)
{
    List<int> canon = Expand(cp, false);
    List<int> comp = Expand(cp, true);
    if (!(rawDecomp[cp].Compat))
    {
        canonical[cp] = canon;
    }

    if (!comp.SequenceEqual(canon) || rawDecomp[cp].Compat)
    {
        compatibility[cp] = comp;
    }
}

int Ccc(int cp) => ccc.TryGetValue(cp, out int v) ? v : 0;

var composition = new SortedDictionary<ulong, int>();
foreach ((int cp, (bool compat, int[] map)) in rawDecomp)
{
    if (compat || map.Length != 2 || exclusions.Contains(cp) || Ccc(cp) != 0 || Ccc(map[0]) != 0)
    {
        continue;
    }

    composition[((ulong)map[0] << 32) | (uint)map[1]] = cp;
}

// Combining class ranges: runs of consecutive code points with the same class.
var ranges = new List<(int Start, int End, int Class)>();
foreach ((int cp, int c) in ccc)
{
    if (ranges.Count > 0 && ranges[^1].End + 1 == cp && ranges[^1].Class == c)
    {
        ranges[^1] = (ranges[^1].Start, cp, c);
    }
    else
    {
        ranges.Add((cp, cp, c));
    }
}

var sb = new StringBuilder();
sb.Append("// <auto-generated>\n");
sb.Append($"// Generated by tools/NormalizationTables from the Unicode Character Database {UcdVersion} (UnicodeData.txt SHA-256 {UnicodeDataSha256},\n");
sb.Append($"// CompositionExclusions.txt SHA-256 {ExclusionsSha256}). Do not edit; see docs/spec/text-normalization-v1.md.\n");
sb.Append("// Unicode data files © Unicode, Inc., used under the Unicode License v3 (see THIRD-PARTY-NOTICES).\n");
sb.Append("// </auto-generated>\n\n");
sb.Append("namespace OneOcr.Unicode;\n\n");
sb.Append("internal static class NormalizationTables\n{\n");
sb.Append($"    public const string UcdVersion = \"{UcdVersion}\";\n\n");

Emit("CccRanges", ranges.SelectMany(r => new[] { r.Start, r.End, r.Class }), "Triples (first code point, last code point, combining class), sorted, for every non-zero class.");
EmitDecomp("Canonical", canonical, "full canonical decomposition");
EmitDecomp("Compat", compatibility, "full compatibility decomposition (only where it differs from the canonical one)");
Emit("CompositionFirst", composition.Keys.Select(k => (int)(k >> 32)), "Primary composites, sorted by (first, second): the first code point of each pair.");
Emit("CompositionSecond", composition.Keys.Select(k => (int)(k & 0xFFFFFFFF)), "The second code point of each pair.");
Emit("CompositionResult", composition.Values, "The composite for each pair.");
sb.Length -= 1; // trailing blank line
sb.Append("}\n");

Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(args[1]))!);
File.WriteAllText(args[1], sb.ToString(), new UTF8Encoding(false));
Console.WriteLine($"ccc ranges {ranges.Count}, canonical {canonical.Count}, compat {compatibility.Count}, compositions {composition.Count}");
return 0;

void Emit(string name, IEnumerable<int> values, string doc)
{
    int[] v = [.. values];
    sb.Append($"    /// <summary>{doc}</summary>\n");
    sb.Append($"    public static ReadOnlySpan<int> {name} =>\n    [\n");
    for (int i = 0; i < v.Length; i += 12)
    {
        sb.Append("        ");
        sb.Append(string.Join(", ", v.Skip(i).Take(12).Select(x => "0x" + x.ToString("X", CultureInfo.InvariantCulture))));
        sb.Append(",\n");
    }

    sb.Append("    ];\n\n");
}

void EmitDecomp(string name, SortedDictionary<int, List<int>> table, string doc)
{
    Emit(name + "Keys", table.Keys, $"Code points with a {doc}, sorted.");
    var offsets = new List<int> { 0 };
    var pool = new List<int>();
    foreach (List<int> m in table.Values)
    {
        pool.AddRange(m);
        offsets.Add(pool.Count);
    }

    Emit(name + "Offsets", offsets, $"Start of each {doc} in the pool (one more entry than keys).");
    Emit(name + "Pool", pool, $"Concatenated {doc}s.");
}

static void Check(string path, string sha)
{
    string actual = Convert.ToHexStringLower(SHA256.HashData(File.ReadAllBytes(path)));
    if (actual != sha)
    {
        throw new InvalidDataException($"{path} hashes to {actual}, expected {sha}");
    }
}
